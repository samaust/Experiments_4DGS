"""Raw annotation counts, deterministic matching and paired camera bootstrap."""
import numpy as np


def divide(numerator, denominator):
    return float(numerator / denominator) if denominator else None


def pixel_counts(prediction, truth, domain):
    p, t = np.asarray(prediction, bool) & domain, np.asarray(truth, bool) & domain
    return dict(tp=int((p & t).sum()), fp=int((p & ~t).sum()), fn=int((~p & t).sum()),
                tn=int((domain & ~p & ~t).sum()), images=1, negative_images=int(not t.any()),
                negative_false_positive_pixels=int(p.sum()) if not t.any() else 0)


def pixel_scores(counts):
    tp, fp, fn = (counts[k] for k in ('tp', 'fp', 'fn'))
    return dict(precision=divide(tp, tp + fp), recall=divide(tp, tp + fn),
                iou=divide(tp, tp + fp + fn), dice=divide(2 * tp, 2 * tp + fp + fn))


def boundary_counts(prediction, truth, domain, tolerance=2):
    from scipy.ndimage import binary_erosion, distance_transform_edt
    # Boundaries generated by ignored/domain cuts are excluded, not scored.
    inner = binary_erosion(domain, structure=np.ones((3, 3), bool), border_value=1)
    p = prediction & ~binary_erosion(prediction, structure=np.ones((3, 3), bool), border_value=0) & inner
    t = truth & ~binary_erosion(truth, structure=np.ones((3, 3), bool), border_value=0) & inner
    return dict(predicted_boundary=int(p.sum()), truth_boundary=int(t.sum()),
                matched_prediction=int((p & (distance_transform_edt(~t) <= tolerance)).sum()) if t.any() else 0,
                matched_truth=int((t & (distance_transform_edt(~p) <= tolerance)).sum()) if p.any() else 0)


def boundary_score(counts):
    if not counts['predicted_boundary'] and not counts['truth_boundary']:
        return None
    if not counts['predicted_boundary'] or not counts['truth_boundary']:
        return 0.
    p = divide(counts['matched_prediction'], counts['predicted_boundary'])
    r = divide(counts['matched_truth'], counts['truth_boundary'])
    return None if p is None or r is None else (2 * p * r / (p + r) if p + r else 0.)


def instance_matching(prediction, truth, prediction_ids, truth_ids, domain):
    """Maximize match count, then total IoU, then lexicographic truth/prediction IDs.

    Hungarian solves the first two objectives. Re-solving the remaining small
    assignment after each truth ID gives deterministic ties without perturbing
    the IoU objective with an arbitrary epsilon.
    """
    from scipy.optimize import linear_sum_assignment
    pi, ti = sorted(prediction_ids), sorted(truth_ids)
    iou = np.zeros((len(ti), len(pi)), np.float64)
    for a, t in enumerate(ti):
        for b, p in enumerate(pi):
            pc = pixel_counts(prediction == p, truth == t, domain)
            iou[a, b] = pixel_scores(pc)['iou'] or 0.
    eligible = iou >= .5
    bonus = min(len(pi), len(ti)) + 1
    weights = np.where(eligible, bonus + iou, 0.)

    def optimum(rows, cols):
        if not rows or not cols:
            return 0.
        r, c = linear_sum_assignment(weights[np.ix_(rows, cols)], maximize=True)
        return float(weights[np.asarray(rows)[r], np.asarray(cols)[c]].sum())

    remaining = list(range(len(pi)))
    matches = []
    target = optimum(list(range(len(ti))), remaining)
    for a, t in enumerate(ti):
        rest = list(range(a + 1, len(ti)))
        choices = [b for b in remaining if eligible[a, b]] + [None]
        for b in choices:
            weight = 0. if b is None else weights[a, b]
            cols = remaining if b is None else [c for c in remaining if c != b]
            value = weight + optimum(rest, cols)
            if np.isclose(value, target, rtol=0, atol=1e-12):
                if b is not None:
                    matches.append(dict(truth_id=t, prediction_id=pi[b], iou=float(iou[a, b])))
                    remaining.remove(b)
                target -= weight
                break
        else:
            raise ValueError('could not preserve the optimal instance assignment')
    return dict(matches=matches, tp=len(matches), fp=len(pi) - len(matches), fn=len(ti) - len(matches),
                unmatched_predictions=[p for p in pi if p not in {m['prediction_id'] for m in matches}],
                unmatched_truth=[t for t in ti if t not in {m['truth_id'] for m in matches}])


def role_precision_bounds(matched_role_count, unmatched_predictions):
    return ([matched_role_count / (matched_role_count + unmatched_predictions), 1.]
            if matched_role_count > 0 else None)


def conditional_domain(domain, truth_labels, metadata, target_role):
    if target_role not in ('player', 'other-person'):
        raise ValueError('unknown annotated person role')
    ignored = [int(i) for i, m in metadata.items()
               if m['class'] == 'person' and m['role'] != target_role]
    return domain & ~np.isin(truth_labels, ignored)


def temporal_counts(first_labels, second_labels, truth_first, truth_second,
                    first_matches, second_matches, associations, domain_first, domain_second):
    m0 = {r['truth_id']: r['prediction_id'] for r in first_matches['matches']}
    m1 = {r['truth_id']: r['prediction_id'] for r in second_matches['matches']}
    counts = dict(visible_successors=0, matched_successors=0, matched_both=0, id_switches=0,
                  missing_successor_matches=0, annotated_births=0, annotated_disappearances=0,
                  false_births=0, false_continuations=0, area_change_errors=[], successor_dice=[])
    for item in associations:
        t0, t1 = item['first_id'], item['second_id']
        p0, p1 = m0.get(t0), m1.get(t1)
        counts['visible_successors'] += int(t1 is not None)
        counts['matched_successors'] += int(t1 is not None and p1 is not None)
        counts['annotated_births'] += int(t0 is None)
        counts['annotated_disappearances'] += int(t1 is None)
        if t0 is not None and t1 is not None:
            counts['missing_successor_matches'] += int(p1 is None)
            counts['matched_both'] += int(p0 is not None and p1 is not None)
            counts['id_switches'] += int(p0 is not None and p1 is not None and p0 != p1)
            a0, a1 = [int(((labels == t) & domain).sum()) for labels, t, domain in
                      [(truth_first, t0, domain_first), (truth_second, t1, domain_second)]]
            b0 = int(((first_labels == p0) & domain_first).sum()) if p0 is not None else 0
            b1 = int(((second_labels == p1) & domain_second).sum()) if p1 is not None else 0
            counts['area_change_errors'].append(divide(abs((b1 - b0) - (a1 - a0)), a1 + a0))
            if p0 is not None:
                mask = second_labels == p1 if p1 is not None else np.zeros_like(domain_second)
                counts['successor_dice'].append(pixel_scores(pixel_counts(mask, truth_second == t1, domain_second))['dice'])
    continued = {m1[r['second_id']] for r in associations if r['first_id'] is not None and
                 r['second_id'] is not None and r['second_id'] in m1 and r['first_id'] in m0 and
                 m0[r['first_id']] == m1[r['second_id']]}
    annotated_birth_predictions = {m1[r['second_id']] for r in associations if r['first_id'] is None and r['second_id'] in m1}
    first_ids = {int(i) for i in np.unique(first_labels) if i > 0}
    second_ids = {int(i) for i in np.unique(second_labels) if i > 0}
    counts['false_births'] = len((second_ids - first_ids) - annotated_birth_predictions)
    counts['false_continuations'] = len((second_ids & first_ids) - continued)
    return counts


def temporal_groups(frames):
    groups = []
    for frame in sorted(set(frames)):
        if not groups or frame != groups[-1][-1] + 1:
            groups.append([])
        groups[-1].append(frame)
    return groups


def paired_bootstrap(method_rows, score, *, resamples=10000, seed=0):
    """Rows keyed (camera, temporal-group) hold additive sufficient statistics.

    Call separately for each branch/role/class/stratum. All methods have exactly
    the same domain; missing groups cannot silently disappear in one method.
    """
    methods = sorted(method_rows)
    if not methods:
        raise ValueError('no paired methods')
    keys = set(method_rows[methods[0]])
    if not keys or any(set(method_rows[m]) != keys for m in methods):
        raise ValueError('missing paired camera/temporal groups')
    cameras = sorted({c for c, _ in keys})
    groups = {c: sorted(g for cam, g in keys if cam == c) for c in cameras}
    fields = sorted(next(iter(method_rows[methods[0]].values())))
    def pooled(method, camera, chosen):
        return {f: sum(method_rows[method][camera, g][f] for g in chosen) for f in fields}
    def mean_defined(values):
        defined = [v for v in values if v is not None]
        return float(np.mean(defined)) if defined else None
    per_camera = {m: {c: score(pooled(m, c, groups[c])) for c in cameras} for m in methods}
    estimates = {m: mean_defined(list(per_camera[m].values())) for m in methods}
    rng = np.random.Generator(np.random.PCG64(seed))
    draws = {m: [] for m in methods}
    for _ in range(resamples):
        sampled_cameras = rng.choice(cameras, len(cameras), replace=True)
        choices = [(int(c), rng.choice(groups[c], len(groups[c]), replace=True)) for c in sampled_cameras]
        for m in methods:
            draws[m].append(mean_defined([score(pooled(m, c, gs)) for c, gs in choices]))
    differences = {}
    for i, a in enumerate(methods):
        for b in methods[i + 1:]:
            ds = [y - x for x, y in zip(draws[a], draws[b]) if x is not None and y is not None]
            interval = np.quantile(ds, [.025, .975], method='linear').tolist() if ds else None
            differences[f'{b}-{a}'] = dict(estimate=estimates[b] - estimates[a] if
                estimates[a] is not None and estimates[b] is not None else None,
                interval_95=interval, defined_resamples=len(ds),
                conclusion='unverified' if interval is None else 'inconclusive' if interval[0] <= 0 <= interval[1] else 'nonzero paired difference')
    return dict(estimates=estimates, per_camera=per_camera,
                per_camera_extrema={m: [min(v for v in per_camera[m].values() if v is not None),
                                       max(v for v in per_camera[m].values() if v is not None)]
                                    if any(v is not None for v in per_camera[m].values()) else None for m in methods},
                undefined_cameras={m: [c for c in cameras if per_camera[m][c] is None] for m in methods},
                differences=differences, resamples=resamples, seed=seed, generator='PCG64', quantile='linear')
