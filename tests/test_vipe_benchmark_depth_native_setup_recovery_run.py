"""Offline D8 setup-recovery worker at its request/result seam (CPU fixture runner)."""
import os
import sys
import unittest
from pathlib import Path
from unittest.mock import patch

from test_vipe_benchmark_depth_native_setup_recovery import CHECKPOINT, JOB, ORIGINAL, WHEELS, NativeSetupRecoveryFixture
from vipe_benchmark.files import file_record, read_json

ORIGINAL_LOCK = ('# autogenerated\nnumpy==1.26.4 \\\n    --hash=sha256:' + 'a' * 64 + '\n'
                 'torch==2.14.1+cu130 \\\n    --hash=sha256:' + 'b' * 64 + '\n')
AMENDED_LOCK = ORIGINAL_LOCK + ''.join(
    f"{row['name']}=={row['version']} \\\n    --hash=sha256:{row['sha256']}\n" for row in WHEELS)


class NativeSetupRecoveryRunTests(NativeSetupRecoveryFixture):
    def setUp(self):
        super().setUp()
        self.raw('jobs/%s/runtime/requirements.lock' % ORIGINAL, ORIGINAL_LOCK.encode())
        self.original['dependency_lock'] = file_record(self.run_root / 'jobs' / ORIGINAL / 'runtime/requirements.lock')
        self.proposal['original_setup'] = self.original
        self.approve()
        self.acquired = []
        self.prepared = []

    def reserve(self):
        from vipe_benchmark.config import load
        from vipe_benchmark.ledger import Ledger
        event = self.authorize()
        ledger = Ledger(self.run_root / 'ledger.jsonl', dict(load(), new_download_gib_limit=110,
                                                              new_artifact_disk_gib_limit=210))
        evidence = {key: event[key] for key in ('request', 'review', 'authorization', 'source_review',
                                                'worker', 'executable')}
        with patch('vipe_benchmark.execution.resources',
                   return_value=dict(download_bytes=10, artifact_bytes=20, gpu_pids=[])):
            reservation = ledger.reserve(JOB, event['command'], evidence, seconds_limit=event['seconds'])
        return reservation

    def snapshot(self, run_root):
        # Baseline first; afterwards the checkpoint and both wheels have been received.
        self.snapshots = getattr(self, 'snapshots', 0) + 1
        received = 0 if self.snapshots == 1 else len(CHECKPOINT) + sum(row['bytes'] for row in WHEELS)
        return dict(download_bytes=10 + received, artifact_bytes=20 + received)

    def acquire(self, url, path, **kwargs):
        self.acquired.append(url)
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(CHECKPOINT)
        return file_record(path)

    def unpack(self, archive, output, revision, **kwargs):
        required = Path(output) / kwargs['required']
        required.parent.mkdir(parents=True)
        required.write_text('fixture native source')

    def prepare(self, lock_text):
        def fake(request, output, config, **kwargs):
            self.prepared.append(dict(request=request, **kwargs))
            runtime = Path(output) / 'runtime'
            runtime.mkdir(parents=True, exist_ok=True)
            (runtime / 'requirements.lock').write_text(lock_text)
            kwargs['lock_check'](lock_text)  # The provisioner gates the lock before installing.
            self.installed = True
            return dict(status='complete', dependency_lock=file_record(runtime / 'requirements.lock'))
        return fake

    def run_worker(self, lock_text=AMENDED_LOCK):
        from vipe_benchmark.depth_setup_other import run_setup_recovery
        reservation = self.reserve()
        output = self.run_root / 'jobs' / JOB
        with patch.dict(os.environ, VIPE_RESERVATION_START=str(reservation['monotonic_start'])), \
                patch('vipe_benchmark.depth_setup_other.budget_snapshot', side_effect=self.snapshot), \
                patch('vipe_benchmark.depth_setup_other._asset_identity'), \
                patch('vipe_benchmark.depth_setup_other._unpack_source', side_effect=self.unpack), \
                patch('vipe_benchmark.depth_setup_other.source_manifest', return_value={'fixture': True}):
            return run_setup_recovery(read_json(self.request['path']), output, request_path=self.request['path'],
                                      acquire=self.acquire, prepare_environment=self.prepare(lock_text))

    def test_retained_archives_reused_and_only_approved_checkpoint_acquired(self):
        original_bytes = {path: path.read_bytes() for path in (self.run_root / 'jobs' / ORIGINAL).rglob('*')
                          if path.is_file()}
        result = self.run_worker()
        self.assertEqual(result['schema'], 'plan069-depth-setup-recovery-result/v1')
        self.assertEqual((result['status'], result['job_id'], result['candidate']), ('complete', JOB, 'D8'))
        self.assertEqual(len(self.acquired), 1)
        self.assertIn('student_pointmap', self.acquired[0])
        self.assertEqual(result['reused_archives'], dict(source_archive=self.original['source_archive'],
                                                         utils3d_archive=self.original['utils3d_archive']))
        self.assertEqual(result['added_packages'], {row['name']: row['version'] for row in WHEELS})
        self.assertTrue((self.run_root / 'jobs' / JOB / 'result.json').is_file())
        self.assertEqual({path: path.read_bytes() for path in original_bytes}, original_bytes)
        constraints = self.prepared[0]['extra_constraints']
        self.assertIn('numpy==1.26.4', constraints)
        self.assertEqual(self.prepared[0]['retained_utils3d'], self.original['utils3d_archive'])

    def test_lock_with_an_unreviewed_package_fails_and_is_preserved(self):
        self.installed = False
        with self.assertRaisesRegex(ValueError, 'acquisition allowlist'):
            self.run_worker(AMENDED_LOCK + 'gradio==9.9.9 \\\n    --hash=sha256:' + 'c' * 64 + '\n')
        self.assertFalse(self.installed, 'refused before any package install')
        failure = read_json(self.run_root / 'jobs' / JOB / 'failure.json')
        self.assertEqual((failure['status'], failure['job_id']), ('failed', JOB))
        self.assertFalse((self.run_root / 'jobs' / JOB / 'result.json').exists())

    def test_wheel_with_a_different_hash_fails(self):
        with self.assertRaisesRegex(ValueError, 'acquisition allowlist'):
            self.run_worker(AMENDED_LOCK.replace(str(WHEELS[0]['sha256']), 'd' * 64))

    def test_changed_retained_archive_is_refused_before_any_transfer(self):
        (self.run_root / 'jobs' / ORIGINAL / 'source.tar.gz').write_bytes(b'changed')
        with self.assertRaises(ValueError):
            self.run_worker()
        self.assertEqual(self.acquired, [])

    def test_existing_output_is_never_reused(self):
        (self.run_root / 'jobs' / JOB).mkdir(parents=True)
        with self.assertRaisesRegex(ValueError, 'immutable'):
            self.run_worker()
        self.assertEqual(self.acquired, [])


if __name__ == '__main__':
    unittest.main()
